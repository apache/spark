package org.apache.spark.sql.catalyst.analysis.resolver

import org.apache.spark.sql.catalyst.expressions.{Alias, Expression, OuterReference}
import org.apache.spark.sql.catalyst.util.toPrettySQL
import org.apache.spark.sql.types.Metadata

/**
 * [[AutoGeneratedAliasProvider]] is a tool to create auto-generated aliases in the plan.
 * All the auto-generated aliases have to be registered in [[ExpressionIdAssigner]].
 */
class AutoGeneratedAliasProvider(expressionIdAssigner: ExpressionIdAssigner) {

  /**
   * Create a new auto-generated [[Alias]]. If the `name` is not provided, it is derived from the
   * child using [[getAliasName]]. We call [[ExpressionIdAssigner.mapExpression]] to register this
   * alias in the [[ExpressionIdAssigner]].
   */
  def newAlias(
      child: Expression,
      name: Option[String] = None,
      explicitMetadata: Option[Metadata] = None,
      qualifier: Seq[String] = Seq.empty): Alias = {
    newAliasImpl(
      child = child,
      name = name,
      explicitMetadata = explicitMetadata,
      qualifier = qualifier
    )
  }

  /**
   * Create a new auto-generated [[Alias]]. If the `name` is not provided, it is derived from the
   * child using [[getAliasName]]. We don't call
   * [[ExpressionIdAssigner.mapExpression]] for outer aliases, because they should be manually
   * mapped in the context of an outer query.
   */
  def newOuterAlias(
      child: Expression,
      name: Option[String] = None,
      explicitMetadata: Option[Metadata] = None): Alias = {
    newAliasImpl(
      child = child,
      name = name,
      explicitMetadata = explicitMetadata,
      skipExpressionIdAssigner = true
    )
  }

  def newAliasImpl(
      child: Expression,
      name: Option[String] = None,
      explicitMetadata: Option[Metadata] = None,
      qualifier: Seq[String] = Seq.empty,
      skipExpressionIdAssigner: Boolean = false): Alias = {
    val alias = Alias(
      child = child,
      name = name.getOrElse(getAliasName(child))
    )(
      explicitMetadata = explicitMetadata,
      qualifier = qualifier
    )
    if (skipExpressionIdAssigner) {
      alias
    } else {
      expressionIdAssigner.mapExpression(alias)
    }
  }

  /**
   * Derive an alias name from the child expression. A bare [[OuterReference]] uses the name of its
   * underlying expression, or its single-pass aggregate alias override when present, to match the
   * fixed-point analyzer. Other expressions use their pretty SQL representation.
   */
  private def getAliasName(child: Expression): String = child match {
    case outerReference: OuterReference =>
      outerReference
        .getTagValue(OuterReference.SINGLE_PASS_OUTER_AGGREGATE_ALIAS_NAME_OVERRIDE)
        .getOrElse(toPrettySQL(outerReference.e))
    case other => toPrettySQL(other)
  }
}
