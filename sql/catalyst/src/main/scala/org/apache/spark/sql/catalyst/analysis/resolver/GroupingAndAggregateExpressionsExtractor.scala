package org.apache.spark.sql.catalyst.analysis.resolver

import java.util.{IdentityHashMap, LinkedHashMap}

import org.apache.spark.SparkException
import org.apache.spark.sql.catalyst.analysis.ValidateSubqueryExpression
import org.apache.spark.sql.catalyst.expressions.{Alias, Attribute, Expression, KllAggregateResolution, NamedExpression}
import org.apache.spark.sql.catalyst.expressions.aggregate.AggregateExpression
import org.apache.spark.sql.catalyst.plans.logical.Aggregate
import org.apache.spark.sql.catalyst.trees.TreePattern.KLL_AGGREGATE

/**
 * Used to extract aggregate and grouping expressions in the context of underlying [[Aggregate]]
 * operator or collecting aggregate expressions based on the provided expression.
 */
class GroupingAndAggregateExpressionsExtractor(
    aggregate: Aggregate,
    autoGeneratedAliasProvider: AutoGeneratedAliasProvider,
    kllSharing: Option[Boolean] = None,
    retainKllChoices: Boolean = true) {

  /**
   * Maps children of aliases from aggregate list to their parents or to `None` if the expression
   * doesn't have an alias. This map only accounts for the first appearance of the expression. For
   * example, for `SELECT col1, col1 AS a` map entry should be (col1 -> None), but for
   * `SELECT col1 AS a, col1` map entry should be (col1 -> Some(a)).
   */
  private val aliasChildToAliasInAggregateExpressions =
    new IdentityHashMap[Expression, Option[Alias]]
  private lazy val aggregateExpressionsSemanticComparator = new SemanticComparator(
    aggregate.aggregateExpressions.map {
      case alias: Alias =>
        aliasChildToAliasInAggregateExpressions.putIfAbsent(alias.child, Some(alias))
        alias.child
      case other =>
        aliasChildToAliasInAggregateExpressions.put(other, None)
        other
    }
  )

  private lazy val legacyKeys = new ValidateSubqueryExpression.LegacyKllDeterminism
  private lazy val legacyExpressionToAttribute = new IdentityHashMap[Expression, Attribute]
  private lazy val legacyAggregateExpressionsSemanticComparator = new SemanticComparator(
    aggregate.aggregateExpressions.map { output =>
      val child = output match {
        case alias: Alias => alias.child
        case other => other
      }
      val key = legacyKeys.expression(child)
      legacyExpressionToAttribute.putIfAbsent(key, output.toAttribute)
      key
    }
  )

  private lazy val localKllAggregates = new IdentityHashMap[Expression, java.lang.Boolean]

  private def hasLocalKllAggregate(expression: Expression): Boolean = {
    if (!expression.containsPattern(KLL_AGGREGATE)) return false
    val cached = localKllAggregates.get(expression)
    if (cached != null) return cached.booleanValue()
    // A scalar subquery's plan is a separate aggregate host.
    val result = expression.isInstanceOf[AggregateExpression] ||
      expression.children.exists(hasLocalKllAggregate)
    localKllAggregates.put(expression, result)
    result
  }

  private val groupingExpressionsSemanticComparator = new SemanticComparator(
    aggregate.groupingExpressions
  )

  // Each alternative indexes the same aggregate host once for all of its sort expressions.
  private lazy val batchExtractor = new GroupingAndAggregateExpressionsExtractor(aggregate,
    autoGeneratedAliasProvider, None, retainKllChoices = false)
  private lazy val correctedExtractor = new GroupingAndAggregateExpressionsExtractor(aggregate,
    autoGeneratedAliasProvider, Some(false), retainKllChoices = false)
  private lazy val legacyExtractor = new GroupingAndAggregateExpressionsExtractor(aggregate,
    autoGeneratedAliasProvider, Some(true), retainKllChoices = false)

  /**
   * Extracts grouping and aggregate expressions based on the provided expression. Instead of
   * provided expression use the extracted one (if any), update `referencedGroupingExpressions`
   * (grouping expressions used for extraction) and `extractedAggregateExpressionAliases` (aliases
   * of [[AggregateExpression]]s that are transformed to attributes during extraction) in order to
   * insert missing attributes to below operators. If a semantically equal expression has already
   * been extracted, instead of aliasing and extracting it again, use an attribute reference to a
   * previously extracted expression.
   *
   * When an expression exists in both grouping and aggregate expressions (for example, when there
   * are lateral column references in [[Aggregate]], LCA algorithm will copy grouping expressions
   * to aggregate list prior to entering this method), we still extract grouping expression but
   * don't add it later if it is not necessary.
   */
  def extractReferencedGroupingAndAggregateExpressions(
      expression: Expression,
      referencedGroupingExpressions: LinkedHashMap[Expression, NamedExpression],
      extractedAggregateExpressionAliases: LinkedHashMap[Expression, Alias]): Expression = {
    if (retainKllChoices && hasLocalKllAggregate(expression)) {
      def resolve(extractor: GroupingAndAggregateExpressionsExtractor): Expression = {
        expression.transformDownWithReferenceEquality {
          case value => extractor.extractReferencedGroupingAndAggregateExpressions(value,
            referencedGroupingExpressions, extractedAggregateExpressionAliases)
        }
      }
      return KllAggregateResolution(
        resolve(batchExtractor), resolve(correctedExtractor), resolve(legacyExtractor))
    }
    def key(value: Expression): Expression = {
      if (!kllSharing.contains(true) && value.containsPattern(KLL_AGGREGATE) &&
          (kllSharing.contains(false) || !value.deterministic)) {
        value
      } else if (kllSharing.contains(true)) {
        legacyKeys.expression(value).canonicalized
      } else {
        value.canonicalized
      }
    }
    val aggregateExpressionWithAlias = collectFirstAggregateExpression(expression)
    val isGroupingExpression = groupingExpressionsSemanticComparator.exists(expression)
    if (isGroupingExpression) {
      if (referencedGroupingExpressions.containsKey(expression.canonicalized)) {
        referencedGroupingExpressions.get(expression.canonicalized).toAttribute
      } else {
        val groupingExpressionReference = aggregateExpressionWithAlias match {
          case (Some(attribute: Attribute), None) => attribute
          case (Some(_), Some(alias)) => alias.toAttribute
          case _ =>
            expression match {
              case attribute: Attribute => attribute
              case other => autoGeneratedAliasProvider.newAlias(child = other)
            }
        }
        referencedGroupingExpressions.put(expression.canonicalized, groupingExpressionReference)
        groupingExpressionReference.toAttribute
      }
    } else {
      aggregateExpressionWithAlias match {
        case (Some(attribute: Attribute), None) => attribute
        case (Some(_), Some(alias)) => alias.toAttribute
        case (Some(expression), None) =>
          throw SparkException.internalError(
            s"No parent alias for expression $expression while extracting aggregate" +
            s"expressions in an operator."
          )
        case _ =>
          expression match {
            case expression: Expression
                if extractedAggregateExpressionAliases.containsKey(key(expression)) =>
              extractedAggregateExpressionAliases.get(key(expression)).toAttribute
            case aggregateExpression: AggregateExpression =>
              val alias = autoGeneratedAliasProvider.newAlias(child = aggregateExpression)
              extractedAggregateExpressionAliases.putIfAbsent(key(alias.child), alias)
              alias.toAttribute
            case other => other
          }
      }
    }
  }

  /**
   * Get first aggregate expression's child that is semantically equal to the provided expression,
   * and it's parent [[Alias]] (if any).
   */
  def collectFirstAggregateExpression(
      expression: Expression): (Option[Expression], Option[Alias]) = {
    if (kllSharing.contains(false) && expression.containsPattern(KLL_AGGREGATE)) {
      return (None, None)
    }
    if (kllSharing.contains(true)) {
      val referencedAggregateExpression = legacyAggregateExpressionsSemanticComparator
        .collectFirst(legacyKeys.expression(expression))
      return (referencedAggregateExpression.map(legacyExpressionToAttribute.get), None)
    }
    val referencedAggregateExpression =
      aggregateExpressionsSemanticComparator.collectFirst(expression)
    referencedAggregateExpression match {
      case Some(expression) =>
        (Some(expression), aliasChildToAliasInAggregateExpressions.get(expression))
      case None =>
        (None, None)
    }
  }

  /**
   * Returns true if the provided expression is semantically equal to any of the aggregate
   * expressions' child.
   */
  def exists(expression: Expression): Boolean = {
    aggregateExpressionsSemanticComparator.exists(expression)
  }
}
