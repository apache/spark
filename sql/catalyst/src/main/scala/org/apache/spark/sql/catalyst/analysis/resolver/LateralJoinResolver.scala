package org.apache.spark.sql.catalyst.analysis.resolver

import java.util.HashMap

import org.apache.spark.sql.catalyst.analysis.AnalysisErrorAt
import org.apache.spark.sql.catalyst.expressions.{
  Attribute,
  Expression,
  ExprId,
  NamedExpression,
  SubExprUtils
}
import org.apache.spark.sql.catalyst.plans.{JoinType, LeftOuter}
import org.apache.spark.sql.catalyst.plans.logical.{LateralJoin, LogicalPlan}
import org.apache.spark.sql.catalyst.util._
import org.apache.spark.sql.types.BooleanType

/**
 * Resolves [[LateralJoin]] by combining the multi-child scope pattern ([[JoinResolver]]) for the
 * left child with the subquery scope pattern ([[SubqueryExpressionResolver]]) for the right side.
 */
class LateralJoinResolver(resolver: Resolver, expressionResolver: ExpressionResolver)
    extends TreeNodeResolver[LateralJoin, LogicalPlan] {
  private val scopes = resolver.getNameScopes
  private val expressionIdAssigner = expressionResolver.getExpressionIdAssigner
  private val queryBlockScopes = resolver.getQueryBlockScopes
  private val cteRegistry = resolver.getCteRegistry
  private val operatorResolutionContextStack = resolver.getOperatorResolutionContextStack
  private val subqueryRegistry = resolver.getSubqueryRegistry
  private val autoGeneratedAliasProvider = expressionResolver.getAutoGeneratedAliasProvider

  /**
   * Resolve [[LateralJoin]]:
   *  1. Resolve the left child in an isolated multi-child scope ([[resolveLeftChild]]).
   *  2. Propagate left output to the parent scope so the lateral subquery can see it.
   *  3. Resolve the lateral subquery plan in a subquery scope ([[resolveLateralSubqueryPlan]]).
   *     [[OuterReference]]s at the subquery's project/aggregate output are aliased during
   *     resolution (via [[ExpressionResolver.aliasOuterReferenceIfNeeded]]), so the right output
   *     has fresh ExprIds and no conflicts with the left side.
   *  4. Fold the right output IDs into the parent [[ExpressionIdAssigner]] mapping.
   *  5. Resolve the optional join condition against the combined left ++ right output.
   *  6. Compute the final output, construct the resolved [[LateralSubquery]], and propagate
   *     outer references to the parent's referenced attributes for [[RetainsOriginalJoinOutput]].
   *
   * {{{
   * SELECT * FROM t1, LATERAL (SELECT c1)
   * -- resolves to:
   * Project [c1#0, c2#1, c1#2]
   * +- LateralJoin lateral-subquery#3 [c1#0], Inner
   *    :  +- SubqueryAlias __auto_generated_subquery_name
   *    :     +- Project [outer(c1#0) AS c1#2]
   *    :        +- OneRowRelation
   *    +- View (t1, [c1#0, c2#1])
   * }}}
   */
  override def resolve(unresolvedLateralJoin: LateralJoin): LogicalPlan = {
    val (resolvedLeft, leftNameScope) = resolveLeftChild(unresolvedLateralJoin)

    expressionIdAssigner.createMappingFromChildMappings(
      newOutputIds = leftNameScope.getOutputIds
    )

    scopes.overwriteCurrent(
      output = Some(leftNameScope.output),
      hiddenOutput = Some(leftNameScope.hiddenOutput),
      qualifiedAccessOnlyOutputIds = Some(leftNameScope.qualifiedAccessOnlyOutputIds)
    )

    val (resolvedSubqueryPlan, rightOutput, outerReferences) =
      resolveLateralSubqueryPlan(unresolvedLateralJoin)

    ExpressionIdAssigner.assertOutputsHaveNoConflictingExpressionIds(
      Seq(leftNameScope.output, rightOutput)
    )

    expressionIdAssigner.createMappingFromChildMappings(
      newOutputIds = leftNameScope.getOutputIds ++ rightOutput.map(_.exprId).toSet,
      mergeIntoExisting = true
    )

    val resolvedCondition = resolveJoinCondition(
      unresolvedLateralJoin = unresolvedLateralJoin,
      leftNameScope = leftNameScope,
      rightOutput = rightOutput
    )

    val newOutput = computeOutput(
      joinType = unresolvedLateralJoin.joinType,
      leftOutput = leftNameScope.output,
      rightOutput = rightOutput
    )

    val newOutputExprIds = newOutput.map(_.exprId).toSet
    val leftHiddenNotInOutput = leftNameScope.hiddenOutput.filter { attribute =>
      !newOutputExprIds.contains(attribute.exprId)
    }

    scopes.overwriteCurrent(
      output = Some(newOutput),
      hiddenOutput = Some(newOutput ++ leftHiddenNotInOutput)
    )

    val resolvedLateralSubquery = unresolvedLateralJoin.right.copy(
      plan = resolvedSubqueryPlan,
      outerAttrs = outerReferences
    )

    operatorResolutionContextStack.current.subqueryExpressionsToValidate
      .add(resolvedLateralSubquery)

    recordOuterReferences(outerReferences, leftNameScope)

    val resolvedLateralJoin = unresolvedLateralJoin.copy(
      left = resolvedLeft,
      right = resolvedLateralSubquery,
      condition = resolvedCondition
    )

    operatorResolutionContextStack.current.baseOperator = Some(resolvedLateralJoin)

    cteRegistry.currentScope.tryPutWithCTE(
      unresolvedOperator = unresolvedLateralJoin,
      resolvedOperator = resolvedLateralJoin
    )
  }

  /**
   * Compute the [[LateralJoin]] output, mirroring [[LateralJoin.output]]: the right side becomes
   * nullable for [[LeftOuter]], and stays as-is for [[Inner]]/[[Cross]] (the only other join types
   * a [[LateralJoin]] permits).
   */
  private def computeOutput(
      joinType: JoinType,
      leftOutput: Seq[Attribute],
      rightOutput: Seq[Attribute]): Seq[Attribute] = joinType match {
    case LeftOuter => leftOutput ++ rightOutput.map(_.withNullability(true))
    case _ => leftOutput ++ rightOutput
  }

  /**
   * Resolve the left child using the multi-child scope pattern: push isolated scopes for
   * [[ExpressionIdAssigner]], [[QueryBlockScopeStack]], [[NameScopeStack]], and [[CteRegistry]],
   * resolve the child, capture the resulting [[NameScope]], then pop all scopes (collecting the
   * child's ID mapping into the parent via `collectChildMapping = true`).
   *
   * Only the left child uses [[CteRegistry.pushScopeForMultiChildOperator]]. Unlike
   * [[JoinResolver]] where both sides are peer branches, the lateral join's right side is a
   * correlated subquery resolved via the subquery scope pattern ([[resolveLateralSubqueryPlan]],
   * which pushes a root CTE scope), so it does not participate in the multi-child scope.
   */
  private def resolveLeftChild(unresolvedLateralJoin: LateralJoin): (LogicalPlan, NameScope) = {
    expressionIdAssigner.pushMapping()
    queryBlockScopes.push()
    scopes.pushScope()
    cteRegistry.pushScopeForMultiChildOperator(
      unresolvedOperator = unresolvedLateralJoin,
      unresolvedChild = unresolvedLateralJoin.left
    )

    try {
      val resolvedLeft = resolver.resolve(unresolvedLateralJoin.left)
      (resolvedLeft, scopes.current)
    } finally {
      cteRegistry.popScope()
      scopes.popScope()
      queryBlockScopes.pop()
      expressionIdAssigner.popMapping(collectChildMapping = true)
    }
  }

  /**
   * Resolve the lateral subquery plan using the subquery scope pattern: push all scopes with
   * `isSubqueryRoot = true`, resolve the inner plan, collect outer references, then pop all
   * scopes.
   *
   * Outer references are collected using [[SubExprUtils.getOuterReferences]]. Only one level of
   * correlation is supported.
   *
   * The subquery mapping is collected on pop (`collectChildMapping = true`) so the caller can fold
   * the right output IDs into the parent mapping via
   * [[ExpressionIdAssigner.createMappingFromChildMappings]].
   */
  private def resolveLateralSubqueryPlan(
      unresolvedLateralJoin: LateralJoin
  ): (LogicalPlan, Seq[Attribute], Seq[Expression]) = {
    expressionIdAssigner.pushMapping(isSubqueryRoot = true)
    queryBlockScopes.push()
    scopes.pushScope(scopeType = NameScopeType.SubqueryRoot)
    cteRegistry.pushScope(isRoot = true)
    subqueryRegistry.pushScope(
      parentOperator = unresolvedLateralJoin,
      autoGeneratedAliasProvider = autoGeneratedAliasProvider,
      outerOperatorResolutionContext = operatorResolutionContextStack.current
    )
    operatorResolutionContextStack.push(
      unresolvedLateralJoin.right.plan,
      isSubqueryRoot = true
    )

    try {
      val resolvedPlan = resolver.resolve(unresolvedLateralJoin.right.plan)
      val rightOutput = scopes.current.output
      val outerReferences = SubExprUtils.getOuterReferences(resolvedPlan)

      (resolvedPlan, rightOutput, outerReferences)
    } finally {
      operatorResolutionContextStack.pop()
      subqueryRegistry.popScope()
      cteRegistry.popScope()
      scopes.popScope()
      queryBlockScopes.pop()
      expressionIdAssigner.popMapping(collectChildMapping = true)
    }
  }

  /**
   * Resolve the optional join condition against the combined output of left and right sides. The
   * scope is temporarily overwritten with `leftOutput ++ rightOutput` for condition resolution.
   *
   * Example -- `SELECT * FROM t1 JOIN LATERAL (SELECT c1 + c2 AS c3) ON c2 = c3`:
   * {{{
   *   Scope during condition resolution: [c1#0, c2#1, c3#2]
   *   Condition resolves: c2 -> c2#1, c3 -> c3#2
   *   Result: EqualTo(c2#1, c3#2) with dataType = BooleanType
   * }}}
   */
  private def resolveJoinCondition(
      unresolvedLateralJoin: LateralJoin,
      leftNameScope: NameScope,
      rightOutput: Seq[Attribute]
  ): Option[Expression] = {
    scopes.overwriteCurrent(
      output = Some(leftNameScope.output ++ rightOutput),
      hiddenOutput = Some(leftNameScope.hiddenOutput)
    )

    val resolvedCondition = unresolvedLateralJoin.condition.map { condition =>
      expressionResolver.resolveExpressionTreeInOperator(
        unresolvedExpression = condition,
        parentOperator = unresolvedLateralJoin
      )
    }

    resolvedCondition.foreach { condition =>
      if (condition.dataType != BooleanType) {
        unresolvedLateralJoin.failAnalysis(
          errorClass = "JOIN_CONDITION_IS_NOT_BOOLEAN_TYPE",
          messageParameters = Map(
            "joinCondition" -> toSQLExpr(condition),
            "conditionType" -> toSQLType(condition.dataType)
          )
        )
      }
    }

    resolvedCondition
  }

  /**
   * Record each leaf [[Attribute]] of the subquery's outer references against the lateral join's
   * scope and context, so the enclosing resolution can react to what the subquery correlated on:
   *  - `referencedAttributes` lets parent operators (e.g. [[ProjectResolver]]) detect hidden
   *    metadata columns via [[RetainsOriginalJoinOutput]].
   *  - `referencedMetadataColumns` lets [[Resolver.insertReferencedMetadataColumnsForOperator]]
   *    push an outer-referenced metadata column (e.g. `_metadata`) down into the left leaf, which
   *    is otherwise missing from the left output (the reference lives only in the subquery).
   *
   * [[SubExprUtils.getOuterReferences]] returns the stripped inner expressions, so an outer
   * reference can be a plain [[NamedExpression]] (e.g. `outer(a)`) or a nested expression over
   * attributes (e.g. `outer(a.b)` yields an [[ExtractValue]]). Both are unwrapped down to their
   * leaf [[Attribute]]s, mirroring [[ExpressionResolver.tryAddReferencedAttribute]].
   */
  private def recordOuterReferences(
      outerReferences: Seq[Expression],
      leftNameScope: NameScope): Unit = {
    val referencedAttributes = expressionResolver.getLastReferencedAttributes
    val referencedMetadataColumns =
      operatorResolutionContextStack.current.referencedMetadataColumns
    outerReferences.foreach {
      case namedExpression: NamedExpression =>
        recordOuterReferencedAttribute(
          attribute = namedExpression.toAttribute,
          leftNameScope = leftNameScope,
          referencedAttributes = referencedAttributes,
          referencedMetadataColumns = referencedMetadataColumns
        )
      case expression =>
        expression.foreach {
          case attribute: Attribute =>
            recordOuterReferencedAttribute(
              attribute = attribute,
              leftNameScope = leftNameScope,
              referencedAttributes = referencedAttributes,
              referencedMetadataColumns = referencedMetadataColumns
            )
          case _ =>
        }
    }
  }

  /**
   * Record a single outer-referenced [[Attribute]] in `referencedAttributes`, and additionally in
   * `referencedMetadataColumns` when it is a metadata column present in the left child's hidden
   * output. Mirrors [[ExpressionResolver.addReferencedAttribute]] for the lateral subquery's outer
   * references.
   */
  private def recordOuterReferencedAttribute(
      attribute: Attribute,
      leftNameScope: NameScope,
      referencedAttributes: HashMap[ExprId, Attribute],
      referencedMetadataColumns: HashMap[ExprId, Attribute]): Unit = {
    referencedAttributes.putIfAbsent(attribute.exprId, attribute)
    if (attribute.isMetadataCol &&
      leftNameScope.getHiddenAttributeById(attribute.exprId).isDefined) {
      referencedMetadataColumns.putIfAbsent(attribute.exprId, attribute)
    }
  }
}
