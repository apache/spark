package org.apache.spark.sql.catalyst.analysis.resolver

import org.apache.spark.SparkException
import org.apache.spark.sql.catalyst.analysis.{
  TableOutputResolver,
  UnresolvedAttribute,
  VariableAssignmentUtils,
  VariableResolution
}
import org.apache.spark.sql.catalyst.expressions.{
  Alias,
  Attribute,
  Expression,
  Literal,
  VariableReference
}
import org.apache.spark.sql.catalyst.plans.logical.{Limit, LogicalPlan, Project, SetVariable}
import org.apache.spark.sql.connector.catalog.CatalogManager
import org.apache.spark.sql.errors.QueryCompilationErrors.unresolvedVariableError
import org.apache.spark.sql.types.IntegerType

/**
 * Resolves scalar SET VARIABLE commands in one bottom-up pass.
 *
 * For an INT variable `v`, `SET VAR v = 1` produces:
 * {{{
 * SetVariable [VariableReference(v)]
 * +- Project [1 AS v]
 *    +- OneRowRelation
 * }}}
 *
 * The resolution matches [[ResolveSetVariable]] in the fixed-point Analyzer.
 */
class SetVariableResolver(
    resolver: LogicalPlanResolver,
    scopes: NameScopeStack,
    autoGeneratedAliasProvider: AutoGeneratedAliasProvider,
    catalogManager: CatalogManager)
    extends TreeNodeResolver[SetVariable, LogicalPlan] {
  private val variableResolution = new VariableResolution(
    tempVariableManager = catalogManager.tempVariableManager,
    catalogManager = catalogManager)

  /**
   * Resolve [[SetVariable]] operator.
   *
   *  1. Resolve the target variables. Targets are resolved before the source so that an unknown
   *     target is reported before source errors.
   *  2. Resolve [[SetVariable.sourceQuery]].
   *  3. Validate the assignment: no duplicate targets.
   *  4. Cast the source columns to the target types using
   *     [[TableOutputResolver.resolveVariableOutputColumns]] and resolve the new cast aliases.
   *  5. Add a `LIMIT 2` unless the source returns at most two rows, which is enough to detect a
   *     multi-row source at execution.
   *  6. Clear the current scope's output, since the command exposes neither visible nor hidden
   *     output.
   *
   * For a BIGINT variable `v`, `SET VAR (v) = (SELECT 1 AS value)` produces:
   * {{{
   * SetVariable [VariableReference(v)]
   * +- Project [cast(value as bigint) AS v]
   *    +- Project [1 AS value]
   *       +- OneRowRelation
   * }}}
   */
  override def resolve(unresolvedSetVariable: SetVariable): LogicalPlan = {
    val resolvedTargets = resolveTargets(
      targetVariables = unresolvedSetVariable.targetVariables,
      searchPathEntriesForError = variableResolution.searchPathEntriesForError)
    val resolvedSource = resolver.resolve(unresolvedSetVariable.sourceQuery)
    val sourceOutput = scopes.current.output

    VariableAssignmentUtils.checkForDuplicateVariables(resolvedTargets)

    val sourceWithCasts = resolveAssignmentCasts(
      setVariable = unresolvedSetVariable,
      resolvedTargets = resolvedTargets,
      resolvedSource = resolvedSource,
      sourceOutput = sourceOutput)
    val sourceWithLimit = addAssignmentCardinalityLimit(sourceWithCasts)
    val resolvedSetVariable = unresolvedSetVariable.copy(
      targetVariables = resolvedTargets,
      sourceQuery = sourceWithLimit)

    scopes.overwriteCurrent(
      output = Some(resolvedSetVariable.output),
      hiddenOutput = Some(Seq.empty))
    resolvedSetVariable
  }

  private def resolveTargets(
      targetVariables: Seq[Expression],
      searchPathEntriesForError: => Seq[Seq[String]]): Seq[VariableReference] = {
    targetVariables.map { target =>
      resolveTarget(
        target = target,
        searchPathEntriesForError = searchPathEntriesForError)
    }
  }

  private def resolveAssignmentCasts(
      setVariable: SetVariable,
      resolvedTargets: Seq[VariableReference],
      resolvedSource: LogicalPlan,
      sourceOutput: Seq[Attribute]): LogicalPlan = {
    val withCasts = TableOutputResolver.resolveVariableOutputColumns(
      expected = resolvedTargets,
      query = resolvedSource,
      conf = conf,
      outputColumns = sourceOutput,
      newAlias = (child, name) =>
        autoGeneratedAliasProvider.newAlias(child = child, name = Some(name)))
    resolveAssignmentCastAliases(
      setVariable = setVariable,
      sourceWithCasts = withCasts,
      resolvedSource = resolvedSource)
  }

  /** Resolves new assignment-cast children in the SET VARIABLE context. */
  private def resolveAssignmentCastAliases(
      setVariable: SetVariable,
      sourceWithCasts: LogicalPlan,
      resolvedSource: LogicalPlan): LogicalPlan = {
    sourceWithCasts match {
      case project: Project if project.child eq resolvedSource =>
        project.copy(projectList = project.projectList.map {
          case alias: Alias =>
            resolveAssignmentCastAlias(alias = alias, setVariable = setVariable)
          case other => other
        })
      case _ =>
        sourceWithCasts
    }
  }

  /** Resolves one assignment-cast alias in the SET VARIABLE context. */
  private def resolveAssignmentCastAlias(alias: Alias, setVariable: SetVariable): Alias = {
    val resolvedChild = resolver.resolveExpressionTreeInOperator(
      unresolvedExpression = alias.child,
      parentOperator = setVariable)
    alias.withNewChildren(Seq(resolvedChild)).asInstanceOf[Alias]
  }

  private def addAssignmentCardinalityLimit(resolvedSource: LogicalPlan): LogicalPlan = {
    if (resolvedSource.maxRows.exists(_ <= 2)) {
      resolvedSource
    } else {
      Limit(Literal(2, IntegerType), resolvedSource)
    }
  }

  private def resolveTarget(
      target: Expression,
      searchPathEntriesForError: => Seq[Seq[String]]): VariableReference = {
    val resolved = target match {
      case unresolvedAttribute: UnresolvedAttribute =>
        variableResolution.lookupVariable(nameParts = unresolvedAttribute.nameParts).getOrElse {
          throw unresolvedVariableError(
            name = unresolvedAttribute.nameParts,
            pathEntries = searchPathEntriesForError,
            origin = unresolvedAttribute.origin)
        }
      case variableReference: VariableReference =>
        variableReference
      case other =>
        throw SparkException.internalError(
          "Unexpected target variable expression in SetVariable: " + other)
    }

    resolved.copy(canFold = false)
  }
}
